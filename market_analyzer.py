"""Explore-mode orchestration: two-stage, evidence-grounded market intelligence."""
from __future__ import annotations

import logging

from groq_helper import GroqClient, LLMError
from rag_engine import RagEngine
from schemas import ExploreInput, validate_explore_overview, validate_explore_strategy
from services import offline, prompts
from services.common import Progress, base_result, merge_evidence, notify, safe_search

log = logging.getLogger("ventureiq.explore")

LIMITATIONS = [
    "Market sizes, growth rates, prices and competitor details are NOT verified research. Any figure shown is an assumption with a stated method.",
    "The bundled knowledge base contains methodology primers, not market statistics. Add your own sourced reports for stronger grounding.",
    "'Source-supported' means the cited knowledge-base passage supports the statement; it does not guarantee the passage itself is correct or current.",
    "Competitors marked potential or illustrative are unconfirmed leads that must be verified from primary sources.",
    "This tool does not provide legal, financial or investment advice.",
]


def run_exploration(inp: ExploreInput, rag: RagEngine | None, llm: GroqClient | None,
                    progress: Progress | None = None, parent_id: int | None = None) -> dict:
    d = inp.as_dict()
    warnings: list[str] = []
    notify(progress, "retrieve", "Retrieving evidence for the idea, industry and business model")
    q1 = f"{inp.industry} {inp.business_model} {inp.stage} market sizing TAM SAM SOM customer discovery validation competitor analysis"
    ev1 = safe_search(rag, q1, warnings, k=6)
    overview = strategy = None
    note, mode, model_name = "", "offline", None
    evidence = ev1
    if llm is None:
        note = "Live AI generation is unavailable (no API key configured). Showing a rule-based offline brief that restates your inputs and applies fixed checklists; it contains no market research."
    else:
        try:
            notify(progress, "stage1", "Stage 1/2 — generating the market overview")
            ids1 = {e.source_id for e in ev1}
            overview = llm.chat_json(prompts.SYSTEM, prompts.explore_user_prompt(d, ev1, 1), lambda x: validate_explore_overview(x, ids1))
            notify(progress, "retrieve2", "Retrieving evidence for strategy, go-to-market and risks")
            q2 = (f"{inp.business_model} go-to-market channels pricing business models risk regulatory funding readiness {inp.stage} "
                  + " ".join(c["name"] for c in overview["competitors"][:3]))
            ev2 = safe_search(rag, q2, warnings, k=6)
            evidence = merge_evidence(ev1, ev2)
            ids2 = {e.source_id for e in evidence}
            notify(progress, "stage2", "Stage 2/2 — generating the strategy analysis")
            strategy = llm.chat_json(prompts.SYSTEM, prompts.explore_user_prompt(d, evidence, 2, overview),
                                     lambda x: validate_explore_strategy(x, ids2))
            mode, model_name = "llm", llm.model
            note = "Generated by a live AI model in two stages from your inputs and retrieved evidence; output validated against the report schema. Treat AI-generated content as hypotheses to verify."
        except LLMError as exc:
            note = f"Live AI generation failed: {exc} Showing a rule-based offline brief instead."
            overview = strategy = None
            evidence = ev1
            log.warning("Explore LLM fallback: %s", type(exc).__name__)
    if overview is None:
        notify(progress, "offline", "Building the rule-based offline brief")
        overview, strategy = offline.offline_explore_report(d, evidence)
    notify(progress, "validate", "Checking claims against retrieved sources")
    notes = overview.get("validation_notes", []) + strategy.get("validation_notes", [])
    notify(progress, "finalize", "Preparing results")
    title = "Idea: " + (inp.idea[:60] + ("…" if len(inp.idea) > 60 else ""))
    res = base_result("explore", title, d, mode, note, model_name, evidence, warnings, list(LIMITATIONS), parent_id)
    res.update({"overview": overview, "strategy": strategy, "validation_notes": notes,
                "summary_line": f"{inp.industry} · {inp.stage} · {mode}"})
    return res
